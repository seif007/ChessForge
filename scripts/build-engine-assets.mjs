#!/usr/bin/env node
/**
 * Generates `src/engine/assets.ts`.
 *
 * Design note — why the wasm is NOT inlined
 * -----------------------------------------
 * The first version base64-inlined the 7.3 MB Stockfish wasm so the WebView
 * needed no filesystem access. That works functionally but breaks the *build*:
 *
 *   - as one literal  -> "Maximum call stack size exceeded" in Babel
 *   - as a `+` chain  -> same (N-deep left-associative binary expression)
 *   - as a chunk array -> parses fine, but Metro/Babel/minifier then spend
 *                         25+ minutes churning a 9.7 MB string constant and
 *                         never finish (measured; a stubbed build takes 3 min)
 *
 * So the wasm is shipped as a real Metro asset (`assets/engine/*.wasm` is
 * already registered in `assetExts`). At runtime `expo-asset` gives us a
 * localUri, and `EngineHost` inlines only the ~21 KB loader plus a tiny
 * bootstrap that fetches the wasm from that URI. The wasm stays a flat binary
 * in the APK — no base64, no 33% size penalty, no parser blowup.
 *
 * Run:  node scripts/build-engine-assets.mjs
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const LOADER = join(root, 'assets/engine/stockfish-18-lite-single.js');
const HOST = join(root, 'src/engine/stockfish-host.js');
const SOUND = join(root, 'src/engine/sound-host.html');
const OUT = join(root, 'src/engine/assets.ts');

for (const f of [LOADER, HOST, SOUND]) {
  if (!existsSync(f)) {
    console.error(`[engine-assets] MISSING: ${f}`);
    process.exit(1);
  }
}

/** Escape for embedding inside a JS template literal. */
function escapeForTemplate(s) {
  return s
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$\{/g, '\\${');
}

const loader = readFileSync(LOADER, 'utf8');
const host = readFileSync(HOST, 'utf8');
const sound = readFileSync(SOUND, 'utf8');

const banner = `/* eslint-disable */
/* AUTO-GENERATED by scripts/build-engine-assets.mjs — DO NOT EDIT BY HAND.
 *
 * Inlined payloads (source text only — the wasm ships as a Metro asset):
 *   loader  ${loader.length.toLocaleString()} chars
 *   host    ${host.length.toLocaleString()} chars
 *   sound   ${sound.length.toLocaleString()} chars
 *
 * The Stockfish wasm is NOT inlined; see the header of
 * scripts/build-engine-assets.mjs for why.
 *
 * Regenerate after replacing any engine/sound file:
 *   node scripts/build-engine-assets.mjs
 */
`;

const out = `${banner}
export const STOCKFISH_LOADER_JS = \`${escapeForTemplate(loader)}\`;

export const STOCKFISH_HOST_JS = \`${escapeForTemplate(host)}\`;

/** Complete HTML document for the hidden WebAudio sound WebView. */
export const SOUND_HOST_HTML = \`${escapeForTemplate(sound)}\`;
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, out, 'utf8');

const wasm = join(root, 'assets/engine/stockfish-18-lite-single.wasm');
const wasmSize = existsSync(wasm) ? statSync(wasm).size : 0;

console.log('[engine-assets] wrote src/engine/assets.ts');
console.log(`  loader  : ${loader.length.toLocaleString()} chars`);
console.log(`  host    : ${host.length.toLocaleString()} chars`);
console.log(`  sound   : ${sound.length.toLocaleString()} chars`);
console.log(`  wasm    : ${wasmSize.toLocaleString()} bytes (shipped as a Metro asset)`);
console.log(`  output  : ${Math.round(out.length / 1024).toLocaleString()} KB`);
