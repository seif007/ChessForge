'use client';

/**
 * Drift mode — step off the line and try your own idea.
 *
 * What this actually is
 * ---------------------
 * ChessForge trains openings by replaying a repertoire: the opponent always answers
 * with the book move, so the trainer only ever asks about positions you already
 * memorised. Drilling has to work that way. But it leaves a real gap — you can
 * recite a line and still have no idea *why* the moves are good, or what
 * happens if you try something else.
 *
 * Drift mode is the answer to "what if I played this instead?". Turn it on and
 * the board stops enforcing the line: you can play any legal move, the engine
 * replies, the eval bar updates live, and a badge tells you at a glance whether
 * you are still inside your repertoire. A "Return to line" control snaps you
 * straight back to where you left, so wandering off is never destructive —
 * you cannot lose your place in the session.
 *
 * This mirrors the exploration already present in the Analysis screen (drag a
 * piece, get live eval, then "Return to game"), deliberately using the same
 * vocabulary so the two screens feel like one feature.
 *
 * Why the badge matters
 * ---------------------
 * Without it, drifting just feels like the app has lost its place. The badge is
 * what makes off-book exploration legible instead of confusing, so it is a core
 * part of the feature rather than decoration.
 */

import { Chess } from 'chess.js';

export type DriftSide = 'w' | 'b';

/** Engine strength while exploring. Capped so suggestions stay human and instructive. */
export const DRIFT_ELO = 2100;

/** How long the exploring engine thinks before proposing a reply. */
export const DRIFT_MOVETIME = 600;

/**
 * Has play left the repertoire?
 *
 * True when a move was played that is not in the recorded line at that point.
 * Drives the badge, so it must stay pure and cheap — it runs on every ply.
 *
 * A shorter `sans` than `line` is *not* drift: the line simply has not finished
 * yet, so the prefix must match exactly.
 */
export function isStillInBook(sans: string[], line: string[]): boolean {
  if (sans.length > line.length) return false;
  for (let i = 0; i < sans.length; i++) {
    if (sans[i] !== line[i]) return false;
  }
  return true;
}

export interface DriftState {
  /** True once play has left the recorded line. */
  drifting: boolean;
  /** Ply at which the departure happened, or null while still on book. */
  driftPly: number | null;
  /** The book move that was available at the departure point. */
  bookMove: string | null;
  /** What was actually played instead. */
  playedMove: string | null;
}

export const ON_BOOK: DriftState = {
  drifting: false, driftPly: null, bookMove: null, playedMove: null,
};

/**
 * Describe the drift status of the current game against the recorded line.
 *
 * `knownLines` is every line that could apply here (mainline plus variations);
 * being inside *any* of them counts as still on book.
 */
export function driftState(sans: string[], knownLines: string[][]): DriftState {
  if (!knownLines.length) return ON_BOOK;

  // Longest prefix any known line shares with what was played.
  let bestPly = 0;
  for (const line of knownLines) {
    let i = 0;
    while (i < sans.length && i < line.length && sans[i] === line[i]) i++;
    if (i > bestPly) bestPly = i;
  }

  if (bestPly >= sans.length) return ON_BOOK;

  const bookMove = knownLines
    .map((l) => l[bestPly])
    .find((m) => m !== undefined) ?? null;

  return {
    drifting: true,
    driftPly: bestPly,
    bookMove,
    playedMove: sans[bestPly] ?? null,
  };
}

/**
 * One-line explanation for the badge, so drift is legible rather than
 * mysterious. Kept short — it sits in a status row.
 */
export function driftDetail(state: DriftState): string {
  if (!state.drifting) return 'Still following your repertoire.';
  const at = state.driftPly === null ? '' : ` at move ${Math.floor(state.driftPly / 2) + 1}`;
  if (state.bookMove && state.playedMove) {
    return `You left the line${at} — played ${state.playedMove} instead of ${state.bookMove}.`;
  }
  return `You left the line${at}. The engine is answering your ideas now.`;
}

/**
 * A legal move generated by the engine for free exploration.
 *
 * Falls back to null (caller keeps the book move) rather than guessing, so
 * exploration can never corrupt the recorded line. The engine call is injected
 * to keep this testable and free of an import cycle with the engine singleton.
 */
export async function exploreReply(
  fen: string,
  search: (fen: string) => Promise<string | null>,
): Promise<{ from: string; to: string; promotion?: string } | null> {
  const uci = await search(fen);
  if (!uci || uci.length < 4 || uci === '(none)') return null;
  const from = uci.slice(0, 2);
  const to = uci.slice(2, 4);
  try {
    // Validate before handing it back: a stale or malformed uci from a
    // timed-out search must not be applied to the board.
    const c = new Chess(fen);
    const m = c.move({ from, to, promotion: uci[4] });
    if (!m) return null;
    return { from: m.from, to: m.to, promotion: m.promotion };
  } catch {
    return null;
  }
}
